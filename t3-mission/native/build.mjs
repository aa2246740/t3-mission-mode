import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const dir = path.dirname(fileURLToPath(import.meta.url));
if (!['darwin', 'linux'].includes(process.platform)) throw new Error('TX_LOCK_BACKEND_UNAVAILABLE: build supports darwin and linux only');
const include = process.argv[2];
if (!include || !fs.existsSync(path.join(include, 'node_api.h'))) throw new Error('Pass the local Node headers directory containing node_api.h. No headers are downloaded.');
const source = path.join(dir, 'mission-lock.c');
const output = path.join(dir, `mission-lock-${process.platform}-${process.arch}.node`);
const args = ['-O2', '-Wall', '-Wextra', '-Werror', '-DNAPI_VERSION=8', '-I', path.resolve(include), ...(process.platform === 'darwin' ? ['-bundle', '-undefined', 'dynamic_lookup'] : ['-shared', '-fPIC']), source, '-o', output];
const result = spawnSync('cc', args, { encoding: 'utf8' });
process.stdout.write(result.stdout || ''); process.stderr.write(result.stderr || '');
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const record = { command: ['cc', ...args], platform: process.platform, arch: process.arch, node: process.version, napi: 8, sourceSha256: hash(source), binarySha256: hash(output) };
fs.writeFileSync(output + '.json', JSON.stringify(record, null, 2) + '\n');
console.log(JSON.stringify(record));
